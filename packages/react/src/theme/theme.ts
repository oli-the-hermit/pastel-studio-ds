import { ACCENT_TOKENS, BASE_ACCENT, type AccentId } from './presets';
import palette from './palette.json';

export type ThemeMode = 'light' | 'dark' | 'system';
export type ResolvedTheme = 'light' | 'dark';

interface PaletteEntry {
  dark: string[];
  light: string[];
  /** Only in a palette generated for an app that has a partner set. */
  partner?: { kind: 'base' | 'alternative'; dark: string[]; light: string[] };
}
const entries = palette as Record<AccentId, PaletteEntry>;

export const isThemeMode = (v: unknown): v is ThemeMode => v === 'light' || v === 'dark' || v === 'system';

/** `system` follows the OS; with no OS preference the app is light. */
export function resolveTheme(mode: ThemeMode, win: Window = window): ResolvedTheme {
  if (mode !== 'system') return mode;
  return win.matchMedia?.('(prefers-color-scheme: dark)').matches ? 'dark' : 'light';
}

/** An accent preset's token values for a theme (palette.json, generated by npm run accents). */
export function accentTokens(accent: AccentId, theme: ResolvedTheme): Record<string, string> {
  const values = (entries[accent] ?? entries[BASE_ACCENT])[theme];
  return Object.fromEntries(ACCENT_TOKENS.map((name, i) => [name, values[i]]));
}

/**
 * Applies a theme and an accent to a document (the main window, a mini player's window, an
 * island). It sets `data-theme` and `color-scheme` on the root and the accent's tokens inline
 * over the stylesheet's, so one call repaints the whole page.
 */
export function applyTheme(mode: ThemeMode, accent: AccentId, doc: Document = document): ResolvedTheme {
  const resolved = resolveTheme(mode, doc.defaultView ?? window);
  const root = doc.documentElement;
  root.dataset.theme = resolved;
  root.style.colorScheme = resolved;
  for (const [name, value] of Object.entries(accentTokens(accent, resolved))) root.style.setProperty(name, value);
  return resolved;
}
